def generate_ibm_credit_like(n_rows: int = 5000, n_users: int = 200, seed: int = SYNTHETIC_SEED) -> pd.DataFrame:
    rng = _rng(seed + 1)
    users = rng.integers(0, n_users, size=n_rows)
    fraud = rng.binomial(1, 0.01, size=n_rows)
    amount = np.round(np.abs(rng.normal(loc=60, scale=90, size=n_rows)) * np.where(fraud == 1, rng.uniform(3, 8, size=n_rows), 1.0), 2)

    days = rng.integers(1, 28, size=n_rows)
    months = rng.integers(1, 13, size=n_rows)
    hours = rng.integers(0, 24, size=n_rows)
    minutes = rng.integers(0, 60, size=n_rows)

    df = pd.DataFrame({
        "User": users,
        "Card": rng.integers(0, 3, size=n_rows),
        "Year": 2026,
        "Month": months,
        "Day": days,
        "Time": [f"{h:02d}:{m:02d}" for h, m in zip(hours, minutes)],
        "Amount": [f"${a:.2f}" for a in amount],
        "Use Chip": rng.choice(["Swipe Transaction", "Chip Transaction", "Online Transaction"], size=n_rows),
        "Merchant Name": rng.integers(10**10, 10**11, size=n_rows),
        "Merchant City": rng.choice(["ONLINE", "New York", "Austin", "Seattle", "Miami"], size=n_rows),
        "Merchant State": rng.choice(["NY", "TX", "WA", "FL", None], size=n_rows),
        "Zip": rng.choice([10001.0, 78701.0, 98101.0, 33101.0, np.nan], size=n_rows),
        "MCC": rng.choice([5411, 5812, 5999, 4900, 5732], size=n_rows),
        "Errors?": rng.choice([None, "Insufficient Balance", "Bad PIN"], size=n_rows, p=[0.92, 0.05, 0.03]),
        "Is Fraud?": np.where(fraud == 1, "Yes", "No"),
    })
    df["_synthetic"] = True
    return df


def _fake_eth_address(i: int) -> str:
    return "0x" + hashlib.sha256(f"synthetic-wallet-{i}".encode()).hexdigest()[:40]


def generate_ethereum_like(n_addresses: int = 800, seed: int = SYNTHETIC_SEED) -> pd.DataFrame:
    rng = _rng(seed + 2)
    flag = rng.binomial(1, 0.08, size=n_addresses)

    sent = rng.integers(0, 200, size=n_addresses)
    received = rng.integers(0, 200, size=n_addresses)
    # Flagged addresses show faster-cycling, higher-fan-out behavior.
    avg_min_sent = np.where(flag == 1, rng.uniform(0.5, 8, size=n_addresses), rng.uniform(30, 5000, size=n_addresses))
    avg_min_received = np.where(flag == 1, rng.uniform(0.5, 8, size=n_addresses), rng.uniform(30, 5000, size=n_addresses))

    total_sent_eth = np.round(rng.exponential(5, size=n_addresses) * np.where(flag == 1, rng.uniform(2, 6, size=n_addresses), 1), 4)
    total_received_eth = np.round(rng.exponential(5, size=n_addresses) * np.where(flag == 1, rng.uniform(2, 6, size=n_addresses), 1), 4)

    df = pd.DataFrame({
        "Address": [_fake_eth_address(i) for i in range(n_addresses)],
        "FLAG": flag,
        "Avg min between sent tnx": np.round(avg_min_sent, 2),
        "Avg min between received tnx": np.round(avg_min_received, 2),
        "Sent tnx": sent,
        "Received Tnx": received,
        "total transactions (including tnx to create contract": sent + received,
        "total Ether sent": total_sent_eth,
        "total ether received": total_received_eth,
        "total ether balance": np.round(total_received_eth - total_sent_eth, 4),
        "Unique Received From Addresses": rng.integers(0, np.maximum(received, 1) + 1),
        "Unique Sent To Addresses": np.where(
            flag == 1,
            rng.integers(5, 30, size=n_addresses),  # fan-out signature
            rng.integers(0, np.maximum(sent, 1) + 1),
        ),
    })
    df["_synthetic"] = True
    return df
